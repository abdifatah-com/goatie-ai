-- ==============================================================================
-- 2. TODOS TABLE (Quickstart & Live Test Route)
-- ==============================================================================
create table if not exists public.todos (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade default auth.uid(),
  name text not null,
  is_complete boolean not null default false,
  inserted_at timestamptz not null default timezone('utc'::text, now())
);

-- Index foreign key and timestamp
create index if not exists idx_todos_user_id on public.todos(user_id);
create index if not exists idx_todos_inserted_at on public.todos(inserted_at desc);

-- Enable RLS
alter table public.todos enable row level security;

-- Grants
grant select, insert, update, delete on public.todos to anon, authenticated;

-- Policies for todos (allows public reading and interacting for testing & demo)
drop policy if exists "Allow public read on todos" on public.todos;
create policy "Allow public read on todos" on public.todos
  for select to anon, authenticated
  using (true);

drop policy if exists "Allow insert on todos" on public.todos;
create policy "Allow insert on todos" on public.todos
  for insert to anon, authenticated
  with check (true);

drop policy if exists "Allow update on todos" on public.todos;
create policy "Allow update on todos" on public.todos
  for update to anon, authenticated
  using (true)
  with check (true);

drop policy if exists "Allow delete on todos" on public.todos;
create policy "Allow delete on todos" on public.todos
  for delete to anon, authenticated
  using (true);

